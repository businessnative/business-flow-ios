// Generates src/engine/unicodeClasses.ts: explicit character-class ranges so the engine
// does not depend on \p{..} support in the JS engine (Hermes). Covers Latin, Greek, Cyrillic, punctuation.
import { writeFileSync } from 'node:fs';
const blocks = [[0x0, 0x52f], [0x1e00, 0x1eff], [0x2000, 0x206f], [0x3000, 0x303f], [0xff00, 0xffef]];
const props = { L: /\p{L}/u, Lu: /\p{Lu}/u, Ll: /\p{Ll}/u, N: /\p{N}/u, P: /\p{P}/u };
const esc = (cp) => '\\u' + cp.toString(16).padStart(4, '0');
const out = {};
for (const [name, re] of Object.entries(props)) {
  const ranges = [];
  for (const [a, b] of blocks) for (let cp = a; cp <= b; cp++) {
    if (!re.test(String.fromCodePoint(cp))) continue;
    const last = ranges[ranges.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp; else ranges.push([cp, cp]);
  }
  out[name] = ranges.map(([x, y]) => (x === y ? esc(x) : esc(x) + '-' + esc(y))).join('');
}
let ts = '// Generated by scripts/gen-unicode.mjs — do not edit.\n';
for (const [k, v] of Object.entries(out)) ts += `export const ${k} = '${v.replace(/\\/g, '\\\\')}';\n`;
writeFileSync(new URL('../src/engine/unicodeClasses.ts', import.meta.url), ts);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
