"""Swift EvalSuite.text -> TypeScript (src/engine/__tests__/evalCases.ts). One-off port helper; source: bn-flow-mac Sources/BNFlowCore/Eval.swift."""
import re, sys, json
src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("public static let text: [EvalCase] = [")
end = src.index("\n    ]\n", start)
body = src[start:end]

def matching(s, i):
    depth, j, instr = 0, i, False
    while j < len(s):
        c = s[j]
        if instr:
            if c == "\\": j += 2; continue
            if c == '"': instr = False
        else:
            if c == '"': instr = True
            elif c in "([": depth += 1
            elif c in ")]":
                depth -= 1
                if depth == 0: return j
        j += 1
    raise ValueError

def split_args(s):
    out, depth, cur, instr, j = [], 0, "", False, 0
    while j < len(s):
        c = s[j]
        if instr:
            cur += c
            if c == "\\": cur += s[j+1]; j += 2; continue
            if c == '"': instr = False
        else:
            if c == '"': instr = True; cur += c
            elif c in "([": depth += 1; cur += c
            elif c in ")]": depth -= 1; cur += c
            elif c == "," and depth == 0: out.append(cur.strip()); cur = ""
            else: cur += c
        j += 1
    if cur.strip(): out.append(cur.strip())
    return out

consts = {"slack": "com.tinyspeck.slackmacgap", "mail": "com.apple.mail", "chrome": "com.google.Chrome", "wa": "net.whatsapp.WhatsApp"}

def conv_value(v):
    v = v.strip()
    if v in consts: return json.dumps(consts[v])
    if v.startswith("."): return json.dumps(v[1:])
    if v in ("true", "false"): return v
    if v.startswith("["):
        inner = v[1:-1]
        return "[" + ", ".join(conv_value(x) for x in split_args(inner)) + "]"
    m = re.match(r"(DictionaryEntry|Snippet)\(", v)
    if m:
        inner = v[len(m.group(1)) + 1:-1]
        return "{ " + ", ".join(conv_kv(x) for x in split_args(inner)) + " }"
    if v.startswith('"'): return v
    raise ValueError(v)

def conv_kv(a):
    k, v = a.split(":", 1)
    return f"{k.strip()}: {conv_value(v)}"

cases = []
i = 0
while True:
    i = body.find("EvalCase(", i)
    if i < 0: break
    j = matching(body, i + len("EvalCase"))
    args = split_args(body[i + len("EvalCase("):j])
    pos, kws = args[:3], args[3:]
    cases.append("  c(" + ", ".join(pos) + ", { " + ", ".join(conv_kv(x) for x in kws) + " }),")
    i = j

out = ["// Generated by scripts/port-eval-cases.py from bn-flow-mac Sources/BNFlowCore/Eval.swift (EvalSuite.text). Do not edit by hand.",
       "import { c } from './evalHelpers';", "", "export const evalCases = ["] + cases + ["];", ""]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
print(len(cases), "cases")
